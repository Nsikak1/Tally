#!/usr/bin/env python3
"""Writes docs/CODE_MAP.md: every source file, its size and a one-line purpose, so a new chat can read this
one page instead of opening the whole code base. Run after changing files:  python3 scripts/code_map.py"""
import os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
KT = os.path.join(ROOT, "app/src/main/java/ng/name/nsikak/libaccession")

def purpose_kt(text: str) -> str:
    m = re.search(r"/\*\*(.*?)\*/\s*(?:@\w+(?:\([^)]*\))?\s*)*(?:private |internal |public )?(?:data |sealed |enum |abstract |open )?(?:class|object|interface|fun)\b", text, re.S)
    if m:
        lines = [re.sub(r"^\s*\*\s?", "", l).strip() for l in m.group(1).strip().splitlines()]
        first = " ".join(l for l in lines if l)[:150]
        if first: return first
    names = re.findall(r"^(?:private |internal )?(?:data |sealed |enum )?(?:class|object|interface|fun)\s+([A-Za-z0-9_]+)", text, re.M)
    return "declares " + ", ".join(names[:6]) if names else ""

def purpose_py(text: str) -> str:
    m = re.match(r'\s*(?:#!.*\n)?\s*"""(.*?)"""', text, re.S)
    return " ".join(m.group(1).strip().split("\n")[0:1]).strip()[:150] if m else ""

rows = []
def add(path, kind):
    text = open(path, encoding="utf-8", errors="replace").read()
    rel = os.path.relpath(path, ROOT)
    p = purpose_kt(text) if kind == "kt" else purpose_py(text) if kind == "py" else (text.split("\n", 2)[1].lstrip("# ").strip()[:150] if text.startswith("#!") and "\n" in text else "")
    rows.append((rel, text.count("\n") + 1, p))

for d, _, files in os.walk(KT):
    for f in sorted(files):
        if f.endswith(".kt"): add(os.path.join(d, f), "kt")
for sub in ("server", "scripts"):
    base = os.path.join(ROOT, sub)
    for f in sorted(os.listdir(base)):
        if f.endswith(".py"): add(os.path.join(base, f), "py")
        elif f.endswith(".sh"): add(os.path.join(base, f), "sh")
rows.sort()

out = ["# Code map (generated by scripts/code_map.py; read this instead of opening every file)", "",
       f"{len(rows)} files, {sum(r[1] for r in rows)} lines.", "", "| file | lines | purpose |", "|---|---:|---|"]
out += [f"| `{r[0].replace('app/src/main/java/ng/name/nsikak/libaccession/', '…/')}` | {r[1]} | {r[2].replace('|', '/')} |" for r in rows]
open(os.path.join(ROOT, "docs/CODE_MAP.md"), "w").write("\n".join(out) + "\n")
print("docs/CODE_MAP.md:", len(rows), "files")
